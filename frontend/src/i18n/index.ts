const dicts: Record<Language, Record<TKey, string>> = { en, ar };

/** The dictionaries themselves, for the coverage gate. `ar` is typed against
 *  `TKey` so a MISSING key is a compile error; what the gate adds is that an
 *  EMPTY one is not, and an empty string renders as nothing at all. */
export const DICTS = dicts;
export const KEYS = Object.keys(en) as TKey[];

let currentLanguage: Language = 'en';

// Components that render translated strings but subscribe to no other store
// would keep last render's language forever. Rather than make every one of them
// subscribe to the settings slice for the side effect, the language is its own
// tiny external store and useT() reads it.
const listeners = new Set<() => void>();

export function setLanguage(lang: Language) {
  // The attribute is set unconditionally. Guarding the whole function on a
  // change meant the very first call — boot, with the default language already
  // current — returned early and never stamped <html lang>, so every English
  // session shipped without it.
  const changed = lang !== currentLanguage;
  currentLanguage = lang;
  document.documentElement.setAttribute('lang', lang);
  // MO10/AX28. `dir` travels with `lang` and always has: this function is the
  // one place that knows the language changed, and having a second owner is
  // how the two got out of step in the first place. `applySideEffects` writes
  // it too, from the same `dirFor`, and agreeing is the point — a language set
  // through any path leaves the document in one state, not two.
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  if (!changed) return; // nothing to re-render
  for (const fn of listeners) fn();
}

export function getLanguage(): Language {
  return currentLanguage;
}

// t translates a key in the current language, falling back to English.
export function t(key: TKey): string {
  return dicts[currentLanguage][key] ?? en[key] ?? key;
}

function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => { listeners.delete(fn); };
}

/**
 * The same t(), but re-rendering the caller when the language changes.
 *
 * Returned identity changes with the language, so it is safe in a dependency
 * array — a memo keyed on it recomputes when it must and not otherwise.
 */
export function useT(): typeof t {
  const lang = useSyncExternalStore(subscribe, getLanguage, getLanguage);
  return useMemo(() => ((key: TKey) => dicts[lang][key] ?? en[key] ?? key), [lang]);
}

// ---- date & time formatting honoring the localization settings ----

const localeFor: Record<Language, string> = { en: 'en-US', ar: 'ar' };

export function formatDate(iso: string | Date, loc: LocalizationSettings): string {
  const d = typeof iso === 'string' ? new Date(iso) : iso;
  if (Number.isNaN(d.getTime())) return '';
  if (loc.dateFormat === 'auto') {
    return d.toLocaleDateString(localeFor[loc.language], { year: 'numeric', month: 'short', day: 'numeric' });
  }
  const dd = String(d.getDate()).padStart(2, '0');
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const yyyy = d.getFullYear();
  switch (loc.dateFormat) {
    case 'dmy': return `${dd}/${mm}/${yyyy}`;
    case 'mdy': return `${mm}/${dd}/${yyyy}`;
    case 'ymd': return `${yyyy}-${mm}-${dd}`;
    default: return d.toLocaleDateString();
  }
}

export function formatTime(iso: string | Date, loc: LocalizationSettings): string {
  const d = typeof iso === 'string' ? new Date(iso) : iso;
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleTimeString(localeFor[loc.language], {
    hour: 'numeric', minute: '2-digit', hour12: loc.timeFormat === '12h',
  });
}

// relativeTime renders "5m ago"-style stamps for notification rows.
export function relativeTime(iso: string, loc: LocalizationSettings): string {
  const then = new Date(iso).getTime();
  if (Number.isNaN(then)) return '';
  const mins = Math.round((Date.now() - then) / 60_000);
  const rtf = new Intl.RelativeTimeFormat(localeFor[loc.language], { numeric: 'auto' });
  if (Math.abs(mins) < 60) return rtf.format(-mins, 'minute');
  const hours = Math.round(mins / 60);
  if (Math.abs(hours) < 24) return rtf.format(-hours, 'hour');
  return rtf.format(-Math.round(hours / 24), 'day');
}
